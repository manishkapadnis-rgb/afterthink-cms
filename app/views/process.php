        // Intersection Observer for Step Animations
        const observerOptions = {
            threshold: 0.3
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('opacity-100', 'translate-y-0');
                    // Update dots
                    const stepNum = entry.target.id.split('-')[1];
                    updateDots(stepNum);
                }
            });
        }, observerOptions);

        document.querySelectorAll('.step-container').forEach(step => {
            step.classList.add('opacity-0', 'translate-y-20', 'transition-all', 'duration-1000', 'ease-out');
            observer.observe(step);
        });

        function updateDots(activeStep) {
            document.querySelectorAll('.step-dot').forEach(dot => {
                const dotStep = dot.getAttribute('data-step');
                if (dotStep === activeStep) {
                    dot.classList.add('w-3', 'h-3', 'bg-tertiary', 'ring-4', 'ring-tertiary/20');
                    dot.classList.remove('w-2', 'h-2', 'bg-outline-variant');
                } else {
                    dot.classList.remove('w-3', 'h-3', 'bg-tertiary', 'ring-4', 'ring-tertiary/20');
                    dot.classList.add('w-2', 'h-2', 'bg-outline-variant');
                }
            });
        }

        // Smooth scroll for dots
        document.querySelectorAll('.step-dot').forEach(dot => {
            dot.addEventListener('click', () => {
                const stepId = `step-${dot.getAttribute('data-step')}`;
                document.getElementById(stepId).scrollIntoView({ behavior: 'smooth', block: 'center' });
            });
        });
    </script>

