<script>
        // Gallery category filtering
        const filters = document.querySelectorAll('.gallery-filter');
        const cards = document.querySelectorAll('#gallery-container .gallery-card');

        filters.forEach(filter => {
            filter.addEventListener('click', () => {
                filters.forEach(f => {
                    f.classList.remove('text-tertiary', 'border-b', 'border-tertiary');
                    f.classList.add('text-on-surface-variant');
                });
                filter.classList.add('text-tertiary', 'border-b', 'border-tertiary');
                filter.classList.remove('text-on-surface-variant');

                const target = filter.getAttribute('data-filter');
                cards.forEach(card => {
                    const match = target === 'all' || card.getAttribute('data-category') === target;
                    card.style.display = match ? '' : 'none';
                    if (match) {
                        card.style.opacity = '0';
                        requestAnimationFrame(() => {
                            card.style.transition = 'opacity .5s ease';
                            card.style.opacity = '1';
                        });
                    }
                });
            });
        });

        // Lightbox
        const lightbox = document.getElementById('lightbox');
        const lightboxImg = document.getElementById('lightbox-img');
        const lightboxTitle = document.getElementById('lightbox-title');
        const lightboxCategory = document.getElementById('lightbox-category');
        const closeLightbox = document.getElementById('close-lightbox');

        function openLightbox(card) {
            const img = card.querySelector('img');
            const title = card.querySelector('h3');
            const category = card.querySelector('span');
            if (!lightbox || !img) return;
            lightboxImg.src = img.currentSrc || img.src;
            lightboxImg.alt = img.alt || '';
            lightboxTitle.textContent = title ? title.textContent : '';
            lightboxCategory.textContent = category ? category.textContent : '';
            lightbox.classList.remove('hidden');
            document.body.style.overflow = 'hidden';
        }
        function hideLightbox() {
            if (!lightbox) return;
            lightbox.classList.add('hidden');
            document.body.style.overflow = '';
        }

        cards.forEach(card => card.addEventListener('click', () => openLightbox(card)));
        if (closeLightbox) closeLightbox.addEventListener('click', hideLightbox);
        if (lightbox) lightbox.addEventListener('click', e => { if (e.target === lightbox) hideLightbox(); });
        document.addEventListener('keydown', e => { if (e.key === 'Escape') hideLightbox(); });

        // Header scroll effect
        window.addEventListener('scroll', () => {
            const header = document.querySelector('header');
            if (!header) return;
            if (window.scrollY > 50) {
                header.classList.add('py-4', 'bg-background/95', 'backdrop-blur-md');
                header.classList.remove('py-6');
            } else {
                header.classList.remove('py-4', 'bg-background/95', 'backdrop-blur-md');
                header.classList.add('py-6');
            }
        });
    </script>

