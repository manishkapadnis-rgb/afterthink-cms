        // Atmospheric counter animation (simplified)
        const counters = document.querySelectorAll('.font-display-lg');
        const options = { threshold: 0.5 };
        
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if(entry.isIntersecting) {
                    const target = entry.target;
                    const endValue = parseInt(target.innerText);
                    // Only animate genuine numeric stats; skip headings/brand
                    // (otherwise non-numeric text is overwritten with "NaN").
                    if (isNaN(endValue)) { observer.unobserve(target); return; }
                    let start = 0;
                    const duration = 2000;
                    const startTime = performance.now();
                    
                    function updateCounter(currentTime) {
                        const elapsed = currentTime - startTime;
                        const progress = Math.min(elapsed / duration, 1);
                        const currentCount = Math.floor(progress * endValue);
                        target.innerText = currentCount + (target.innerText.includes('+') ? '+' : '');
                        
                        if (progress < 1) {
                            requestAnimationFrame(updateCounter);
                        } else {
                            target.innerText = endValue + (target.innerText.includes('+') ? '+' : '');
                        }
                    }
                    requestAnimationFrame(updateCounter);
                    observer.unobserve(target);
                }
            });
        }, options);

        counters.forEach(counter => observer.observe(counter));
